// Generates packages/preview/scene/studio.hdr: the one fixed, neutral studio environment used for
// every preview and on the site. It is made by this script (no photograph), so it is CC0 like the
// rest of the generated content, and nothing is fetched at render time.
//
// The map is 256 × 128, equirectangular, in Radiance RGBE format: a soft grey dome that is brighter
// overhead, one large soft key light at the upper front-left, a weaker fill at the right, and a
// darker warm-grey ground. Run: node tools/hdri/build.ts
import { writeFileSync } from "node:fs";
import path from "node:path";

const W = 256;
const H = 128;

type RGB = [number, number, number];

/** Soft circular light: 1 at its centre, falling smoothly to 0 at `radius` (radians). */
function blob(dir: number[], centre: number[], radius: number): number {
  const d = Math.acos(
    Math.max(
      -1,
      Math.min(
        1,
        (dir[0] as number) * (centre[0] as number) +
          (dir[1] as number) * (centre[1] as number) +
          (dir[2] as number) * (centre[2] as number),
      ),
    ),
  );
  if (d >= radius) return 0;
  const t = 1 - d / radius;
  return t * t * (3 - 2 * t);
}

function unit(x: number, y: number, z: number): number[] {
  const l = Math.hypot(x, y, z);
  return [x / l, y / l, z / l];
}

const KEY = unit(-0.6, 0.75, 0.7); // upper front-left (front is +Z)
const FILL = unit(0.9, 0.35, 0.3); // right

function radiance(dir: number[]): RGB {
  const y = dir[1] as number;
  if (y < 0) {
    // Ground: darker, slightly warm, fading towards the horizon.
    const g = 0.18 + 0.1 * (1 + y);
    return [g * 1.02, g, g * 0.96];
  }
  const dome = 0.55 + 0.45 * y; // brighter overhead
  const key = 6.0 * blob(dir, KEY, 0.55);
  const fill = 1.6 * blob(dir, FILL, 0.7);
  const v = dome + key + fill;
  return [v, v, v * 1.01];
}

function toRgbe([r, g, b]: RGB): [number, number, number, number] {
  const v = Math.max(r, g, b);
  if (v < 1e-32) return [0, 0, 0, 0];
  const e = Math.ceil(Math.log2(v));
  const scale = 256 / 2 ** e;
  return [
    Math.min(255, Math.floor(r * scale)),
    Math.min(255, Math.floor(g * scale)),
    Math.min(255, Math.floor(b * scale)),
    e + 128,
  ];
}

const header = `#?RADIANCE\n# Prop Commons studio environment, generated by tools/hdri/build.ts (CC0-1.0)\nFORMAT=32-bit_rle_rgbe\n\n-Y ${H} +X ${W}\n`;
const pixels = new Uint8Array(W * H * 4);
for (let j = 0; j < H; j++) {
  const theta = ((j + 0.5) / H) * Math.PI; // 0 at the top
  for (let i = 0; i < W; i++) {
    // Three.js equirect mapping: u = 0.5 at -Z... use atan2(x, -z) so +Z (front) maps to the edges.
    const phi = ((i + 0.5) / W) * 2 * Math.PI - Math.PI;
    const dir = [
      Math.sin(theta) * Math.sin(phi),
      Math.cos(theta),
      -Math.sin(theta) * Math.cos(phi),
    ];
    pixels.set(toRgbe(radiance(dir)), (j * W + i) * 4);
  }
}
// Flat (uncompressed) scanlines; the first pixel must not look like an RLE marker (2, 2).
if (pixels[0] === 2 && pixels[1] === 2) pixels[0] = 3;
const out = path.join(import.meta.dirname, "../../packages/preview/scene/studio.hdr");
writeFileSync(out, Buffer.concat([Buffer.from(header, "ascii"), pixels]));
console.log(`Wrote ${out}`);
